/**
 * Gallery page: the plane.
 *
 * The set is the studio's own event photography, harvested scene by scene from
 * the photographer's galleries — Arrival, Sufi Night, Mehendi, Sangeet, Haldi,
 * Wedding, Roka, Carnival and the rest. It was filtered first to frames with no
 * detected face, then by eye off a contact sheet to drop the guests the detector
 * missed because they were in profile, turned away, or small in a wide shot.
 * What is left is the work: the rooms, the installations, the lighting and the
 * details. No client is identifiable, which is the portfolio's own condition.
 *
 * The shots are listed by category. `ar` is the real width / height of the
 * file: the grid crops every photograph to one 4:5 cell, and the lightbox uses
 * the ratio to size its frame before the file arrives, so nothing shifts on
 * load. Files are /gallery/<id>-s.webp (650px on the long side) for the grid and
 * /gallery/<id>-l.webp (1400px) for the lightbox.
 *
 * The bar's strings are the main site's own: the photographer's credit, the
 * "Gallery" tab that shows every event, and the count line under the tabs.
 */

